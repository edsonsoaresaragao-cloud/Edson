CREATE TABLE "DiagnosticCase" (
 "id" TEXT NOT NULL PRIMARY KEY, "ownerId" TEXT NOT NULL REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "data" JSONB NOT NULL, "revision" INTEGER NOT NULL DEFAULT 1,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "DiagnosticCase_ownerId_updatedAt_idx" ON "DiagnosticCase"("ownerId","updatedAt");
CREATE TABLE "DiagnosticTechnicalEntry" (
 "id" TEXT NOT NULL PRIMARY KEY, "kind" TEXT NOT NULL, "data" JSONB NOT NULL, "published" BOOLEAN NOT NULL DEFAULT FALSE,
 "editorId" TEXT NOT NULL REFERENCES "User"("id") ON DELETE RESTRICT ON UPDATE CASCADE, "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "DiagnosticTechnicalEntry_published_kind_idx" ON "DiagnosticTechnicalEntry"("published","kind");
